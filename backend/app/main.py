@app.get("/api/prospects", response_model=List[Organization])
def list_prospects(
    search_id: Optional[str] = None,
    industry: Optional[str] = None,
    location: Optional[str] = None,
    min_icp_score: Optional[int] = None,
    validation_status: Optional[str] = None,
    confidence: Optional[str] = None,
    sort_by: Optional[str] = Query("icp_score", enum=["icp_score", "confidence", "employees", "name"])
):
    """Fetch discovered prospects with multi-attribute filtering & sorting."""
    results = list(db.organizations.values())

    if search_id:
        results = [o for o in results if o.search_id == search_id]
    if industry and industry != "All":
        results = [o for o in results if industry.lower() in o.industry.lower()]
    if location and location != "All":
        results = [o for o in results if location.lower() in o.location.lower()]
    if min_icp_score:
        results = [o for o in results if o.icp_match_score >= min_icp_score]
    if validation_status and validation_status != "All":
        results = [o for o in results if o.validation_status.value == validation_status]
    if confidence and confidence != "All":
        results = [o for o in results if o.confidence.value == confidence]

    # Sorting
    if sort_by == "icp_score":
        results.sort(key=lambda x: x.icp_match_score, reverse=True)
    elif sort_by == "employees":
        results.sort(key=lambda x: x.employee_count, reverse=True)
    elif sort_by == "name":
        results.sort(key=lambda x: x.name)

    return results

