@app.delete("/api/searches/{search_id}")
def delete_search(search_id: str):
    """Delete a search record and its associated prospects."""
    if search_id in db.searches:
        del db.searches[search_id]
        # Remove associated orgs
        to_del = [oid for oid, o in db.organizations.items() if o.search_id == search_id]
        for oid in to_del:
            del db.organizations[oid]
        return {"status": "success", "message": f"Search {search_id} deleted"}
    raise HTTPException(status_code=404, detail="Search record not found")

