@app.get("/api/reviews", response_model=List[HumanReviewItem])
def list_human_reviews(status: Optional[str] = None):
    """List pending or resolved Human-in-the-Loop review items."""
    revs = list(db.human_reviews.values())
    if status:
        revs = [r for r in revs if r.status == status]
    return revs

@app.post("/api/reviews/{review_id}/action")
def resolve_human_review(
    review_id: str,
    action: str = Body(..., embed=True),  # "approve_a", "approve_b", "mark_uncertain", "rerun"
    selected_option: Optional[str] = Body(None, embed=True)
):
    """Submit human approval or decision override for data conflict."""
    if review_id not in db.human_reviews:
        raise HTTPException(status_code=404, detail="Review item not found")
    rev = db.human_reviews[review_id]
    rev.status = "approved" if "approve" in action else "resolved"
    rev.selected_option = selected_option or action

    # Update associated org validation status
    if rev.organization_id in db.organizations:
        org = db.organizations[rev.organization_id]
        org.validation_status = ValidationStatus.VERIFIED
        org.confidence = ConfidenceLevel.HIGH

    return {"status": "success", "review": rev}

